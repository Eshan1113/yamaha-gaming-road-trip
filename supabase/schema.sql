-- Run once in Supabase Dashboard -> SQL Editor -> New Query
-- Creates the public.game_scores table and allows public kiosk read/insert via RLS.

CREATE TABLE IF NOT EXISTS public.game_scores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_name text NOT NULL,
  phone text,
  score integer NOT NULL DEFAULT 0,
  play_time integer NOT NULL DEFAULT 30,
  result_status text NOT NULL DEFAULT 'FAILED',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_game_scores_score_created
  ON public.game_scores (score DESC, created_at ASC);

ALTER TABLE public.game_scores ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read game_scores" ON public.game_scores;
CREATE POLICY "Allow public read game_scores"
  ON public.game_scores
  FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow public insert game_scores" ON public.game_scores;
CREATE POLICY "Allow public insert game_scores"
  ON public.game_scores
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);
