-- Run once in Supabase Dashboard -> SQL Editor -> New Query
-- Creates the public.leaderboard_entries table and allows public kiosk read/insert via RLS.

CREATE TABLE IF NOT EXISTS public.leaderboard_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_name text NOT NULL,
  mobile_number text NOT NULL,
  score integer NOT NULL DEFAULT 0,
  markers_collected integer NOT NULL DEFAULT 0,
  obstacles_avoided integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_leaderboard_entries_score_created
  ON public.leaderboard_entries (score DESC, created_at ASC);

ALTER TABLE public.leaderboard_entries ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read leaderboard" ON public.leaderboard_entries;
CREATE POLICY "Allow public read leaderboard"
  ON public.leaderboard_entries
  FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow public insert leaderboard" ON public.leaderboard_entries;
CREATE POLICY "Allow public insert leaderboard"
  ON public.leaderboard_entries
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);
